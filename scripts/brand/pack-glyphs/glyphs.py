def _laurel():
    out = []
    for side in (1, -1):
        cx, cy, R = 60, 60, 38
        # branch as thin arc band
        a0, a1 = 250, 150  # from bottom going up the side (right side uses mirrored angles)
        band = []
        steps = 12
        for i in range(steps + 1):
            a = math.radians(-70 + (190 - (-70)) * 0 + 0)
        # leaves
        for i in range(7):
            t = i / 6
            ang = math.radians(-78 + t * 150)  # right side: from bottom (-78) up to top (72)
            px, py = cx + side * R * math.cos(ang), cy - R * math.sin(ang)
            # leaf direction: tangent (upwards along the wreath) tilted outward
            tx, ty = -math.sin(ang), -math.cos(ang)
            tx *= side
            L = 17 - t * 5
            W = 7 - t * 2
            for o in (1, -1):
                ox, oy = side * math.cos(ang) * o, -math.sin(ang) * o
                dx, dy = tx * 0.75 + ox * 0.66, ty * 0.75 + oy * 0.66
                n = math.hypot(dx, dy)
                dx, dy = dx / n, dy / n
                bx, by = px + dx * 2, py + dy * 2
                ex, ey = bx + dx * L, by + dy * L
                nx, ny = -dy, dx
                mx, my = bx + dx * L * 0.45, by + dy * L * 0.45
                out.append([(bx, by), (mx + nx * W / 2, my + ny * W / 2), (ex, ey), (mx - nx * W / 2, my - ny * W / 2)])
        stem = []
        for i in range(13):
            ang = math.radians(-84 + i * 13)
            stem.append((cx + side * (R + 1.6) * math.cos(ang), cy - (R + 1.6) * math.sin(ang)))
        for i in reversed(range(13)):
            ang = math.radians(-84 + i * 13)
            stem.append((cx + side * (R - 1.6) * math.cos(ang), cy - (R - 1.6) * math.sin(ang)))
        out.append(stem)
    return out


G['laurel'] = _laurel()


