def _zig(y0, t=13, n=4, x0=6, x1=114):
    step = (x1 - x0) / n
    h = step / 2 * math.tan(math.radians(52)) / 2.2
    top, bot = [], []
    for i in range(n + 1):
        x = x0 + i * step
        top.append((x, y0))
        if i < n:
            top.append((x + step / 2, y0 - h))
    for x, y in reversed(top):
        bot.append((x, y + t))
    return top + bot


