def _tail(cx=50, cy=54, r=27):
    segs = []
    spans = [(212, 180), (176, 144), (140, 108), (104, 72), (68, 40)]
    for i, (a0, a1) in enumerate(spans):
        w = 13 - i * 1.4
        pts = []
        for a in (a0, a1):
            t = math.radians(a)
            pts.append((cx + (r + w / 2) * math.cos(t), cy - (r + w / 2) * math.sin(t)))
        for a in (a1, a0):
            t = math.radians(a)
            pts.append((cx + (r - w / 2) * math.cos(t), cy - (r - w / 2) * math.sin(t)))
        segs.append(pts)
    return segs


