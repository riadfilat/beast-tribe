def _tally():
    bars = [(20, 29), (40, 49), (60, 69), (80, 89)]
    y0, y1 = 20, 100
    # slash band: centre line from (8, 88) to (112, 34), half-thickness 6, plus a 4-unit gap each side
    ax, ay, bx, by = 8, 88, 112, 34
    slope = (by - ay) / (bx - ax)
    half, gap = 6.0, 4.0
    def yc(x):
        return ay + slope * (x - ax)
    out = []
    k = math.sqrt(1 + slope * slope)
    for l, r in bars:
        # band edges (vertical offsets) at bar sides, including the gap
        off = (half + gap) * k
        out.append([(l, y0), (r, y0), (r, yc(r) - off), (l, yc(l) - off)])
        out.append([(l, yc(l) + off), (r, yc(r) + off), (r, y1), (l, y1)])
    off = half * k
    out.append([(ax, ay - off), (bx, by - off), (bx, by + off), (ax, ay + off)])
    return out


G['tally'] = _tally()


