def _mirror(half, cx=60):
    """half: points on the right side, top to bottom; returns a closed symmetric outline."""
    right = list(half)
    left = [(2 * cx - x, y) for x, y in reversed(half)]
    return right + left


def _rot(pts, deg, cx=60, cy=60):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    return [(cx + (x - cx) * c - (y - cy) * s, cy + (x - cx) * s + (y - cy) * c) for x, y in pts]


